#!/usr/bin/env python3
"""
capture_environment.py -- record the interpreter and package versions that
produced the published runs, as provenance/ENVIRONMENT.md.

Run it with the SAME interpreter you used for the study runs, from the
repository root:

    python scripts/capture_environment.py > provenance/ENVIRONMENT.md

Do not run it under `python -I`: isolated mode hides user site-packages, so
the report would omit packages the runs actually used.
"""

import datetime
import importlib
import platform
import subprocess
import sys

PACKAGES = ["numpy", "scipy", "torch", "sklearn", "pandas"]
DISPLAY = {"sklearn": "scikit-learn"}


def version_of(name):
    try:
        mod = importlib.import_module(name)
    except Exception as e:
        return None, f"not importable ({type(e).__name__})"
    v = getattr(mod, "__version__", None)
    if v is None:
        try:
            from importlib.metadata import version as md_version
            v = md_version(DISPLAY.get(name, name))
        except Exception:
            v = "unknown"
    return v, None


def git_commit():
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, timeout=10)
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    except Exception:
        pass
    return None


def main():
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%d %H:%M UTC")
    commit = git_commit()

    print("# Environment of record")
    print()
    print(f"Recorded {stamp} from the interpreter below.")
    if commit:
        print(f"Repository at commit `{commit}`.")
    print("Generated by `scripts/capture_environment.py`; do not hand-edit.")
    print()
    print("## Interpreter")
    print()
    print(f"- Python: {sys.version.split()[0]} ({platform.python_implementation()})")
    print(f"- Build: {platform.platform()}")
    print(f"- Executable: `{sys.executable}`")
    print()
    print("## Packages")
    print()
    print("| Package | Version |")
    print("|---|---|")
    missing = []
    for name in PACKAGES:
        v, err = version_of(name)
        label = DISPLAY.get(name, name)
        if err:
            print(f"| {label} | {err} |")
            missing.append(label)
        else:
            print(f"| {label} | {v} |")
    print()
    if missing:
        print(f"Not importable here: {', '.join(missing)}. If any of these were")
        print("used for the published runs, re-run this under the interpreter")
        print("that has them.")
        print()
    print("## Note on reproducibility")
    print()
    print("`requirements.txt` states compatible ranges, not exact pins. The")
    print("table above records the one configuration under which the reported")
    print("numbers were produced. Seeded results are expected to be identical")
    print("under this configuration and are not guaranteed bit-identical")
    print("under other versions within those ranges, particularly across the")
    print("numpy 1.x to 2.x boundary.")


if __name__ == "__main__":
    main()
